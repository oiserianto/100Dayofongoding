// Day 30 Operator perbandingan <= dan >=
// <= lebih kecil atau sama dengan
// >= lebih besar atau sama dengan
public class Day30 {
    public static void main(String[] args) {
       
        // Menyimpan nilai pertama
        int A = 30;

        // Menyimpan nilai kedua
        int B = 35;

        // Mengecek apakah nilaiA lebih kecil atau sama dengan nilaiB
        boolean hasil1 = A <= B;

        // Mengecek apakah nilaiA lebih besar atau sama dengan nilaiB
        boolean hasil2 = A >= B;

        // Menampilkan hasil perbandingan
        System.out.println("30 <=35: " + hasil1);
        System.out.println("30 >=35: " + hasil2);
    }
}
