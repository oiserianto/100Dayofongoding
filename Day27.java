// Day26 Operator Increment dan Decrement (++,--)
public class Day27 {
    public static void main(String[] args) {
       int angka = 10;
       System.out.println("Nilai awal\t\t: "+angka);
       angka++;
       System.out.println("Sebelum increment\t: "+angka);
       angka--;
       System.out.println("Setelah decrement\t: "+angka);
        
    }
}
