 /**
 * Day29 Operator Perbandingan < dan >
 * operator perbandingan digunakan untuk membandingkan dua nilai
 * < lebih keci > lebih besar
 */
public class Day29 {
    public static void main(String[] args) {

        // Membuat variabel a dengan nilai 10
        int a = 10;

        // Membuat variabel b dengan nilai 20
        int b = 20;

        // Mengecek apakah a lebih kecil dari b
        System.out.println(a < b);

        // Mengecek apakah a lebih besar dari b
        System.out.println(a > b);
    }
}
